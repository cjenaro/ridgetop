// Crownshard unit animation library: combat stances, shared keyframe clips, and
// archetype-aware clip selection. Pure data + pure functions (no DOM), shared by the
// battle scene, the camp diorama, and the baked portrait generator.
//
// Joint conventions (framework character builder, character faces +Z):
//   root at the feet; body/head/armL/armR/legL/legR/cape.
//   arm/leg pitch < 0 swings the limb forward/up (-PI = straight overhead).
//   body pitch > 0 leans forward; root pitch < 0 topples backward around the feet.
//   armR roll > 0 / armL roll < 0 abducts the arm outward. armR = main hand, armL = off hand.
import type { AnimationClip, Easing, JointPose, Keyframe } from 'ridgetop'
import type { EnemyArchetypeId, HeroClassId } from './types.ts'

type V3 = [number, number, number]

/** Compact keyframe helper: rotation (pitch, yaw, roll), optional position and easing into this key. */
function k(t: number, rotation?: V3, position?: V3, ease?: Easing): Keyframe {
  return { t, rotation, position, ease }
}
/** Position-only keyframe helper. */
function p(t: number, position: V3, ease?: Easing): Keyframe {
  return { t, position, ease }
}

// =========================================================================
// COMBAT STANCES (additive, layered onto idle-family clips)
