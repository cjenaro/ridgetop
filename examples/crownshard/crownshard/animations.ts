/** Stable [0,1) hash for a uid so per-unit phase/variant choices don't drift between frames. */
export function uidHash(uid: string): number {
  let h = 2166136261
  for (let i = 0; i < uid.length; i++) {
    h ^= uid.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return ((h >>> 0) % 100000) / 100000
}
