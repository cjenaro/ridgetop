/** Which side of the defender a blow arrives from (relative to its facing). */
export type HitArc = 'front' | 'flank' | 'back'

/** Directional hit reaction; `side` is the defender's side the blow came from. */
export function hitClipFor(arc: HitArc, side: 'left' | 'right', heavy: boolean): UnitClipName {
  if (arc === 'back') return 'hit_back'
  if (arc === 'flank') return side === 'left' ? 'hit_flank_l' : 'hit_flank_r'
  return heavy ? 'hit_heavy' : 'hit'
}

/** Facing-pivot footwork; the scene rotates the unit's yaw while this plays. */
export function turnClipFor(dir: 'left' | 'right' | 'about'): UnitClipName {
  return dir === 'left' ? 'turn_l' : dir === 'right' ? 'turn_r' : 'turn_about'
}

/** One-shot reaction when a status effect lands. */
export function statusClipFor(status: StatusKind): UnitClipName {
  if (status === 'burn' || status === 'poison') return 'status_burn'
  if (status === 'slow') return 'status_freeze'
  if (status === 'stun') return 'status_stun'
  if (status === 'taunt') return 'taunt'
  return 'status_empower'
}

/** Archetype death; every death is still by ~0.9 s so the scene can sink the body from 1.0 s. */
export function deathClipFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId, isBoss?: boolean): UnitClipName {
  if (
    enemyId === 'frost_golem' || enemyId === 'orc_brute' ||
    enemyId === 'river_troll' || enemyId === 'briar_warlord' ||
    enemyId === 'magma_warden' || enemyId === 'frostwyrm_rimefang' || enemyId === 'ignis_titan'
  ) return 'death_crumble'
  if (
    enemyId === 'eclipse_archon' || isBoss || enemyId === 'bog_shaman' ||
    enemyId === 'ice_wraith' || enemyId === 'ember_pyromancer' ||
    enemyId === 'bone_necromancer' || enemyId === 'mire_matriarch' ||
    enemyId === 'ash_inquisitor' || enemyId === 'lich_vaelen'
  ) return 'death_dissolve'
  if (enemyId === 'goblin' || enemyId === 'bone_thrall') return 'death_tumble'
  if (heroId === 'knight' || heroId === 'paladin' || heroId === 'champion' || enemyId === 'crypt_knight' || enemyId === 'frost_jarl' || enemyId === 'abyssal_sentinel') return 'death_kneel'
  return 'death'
}

/** Skill/spell clip: casters raise both hands, archers draw a power shot, melee heroes rally with a raised weapon. */
export function castClipFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): UnitClipName {
  const a = archetypeOf(heroId, enemyId)
  if (a === 'bow') return 'attack_bow'
  if (a === 'caster') return 'cast'
  return 'cast_rally'
}

/** Pre-attack aim/wind-up loop clip while previewing an attack or skill against a target (weapon-aware for heroes). */
export function aimClipFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId, isSkill = false, weaponId?: string): UnitClipName {
  if (heroId && weaponId) {
    const attack = attackClipFor(heroId, undefined, weaponId)
    if (attack === 'attack_bow') return 'aim_bow'
    if (attack === 'attack_staff' && !isSkill) return 'aim_cast'
    if (attack === 'attack_thrust' || attack === 'attack') return 'aim_melee'
  }
  const a = archetypeOf(heroId, enemyId)
  if (a === 'bow') return 'aim_bow'
  if (a === 'caster') return 'aim_cast'
  if (isSkill && (heroId === 'paladin' || heroId === 'knight')) return 'aim_heavy'
  if (heroId === 'paladin') return 'aim_heavy'
  if (a === 'heavy') return 'aim_heavy'
  return 'aim_melee'
}

/** Idle variant: heroes stand proud, enemies hunch and scan; wounded units sag (heroes) or cower (enemies); stunned units sway. */
export function idleClipFor(team: 'ally' | 'enemy', hpRatio: number, stunned: boolean): UnitClipName {
  if (stunned) return 'dizzy'
  if (hpRatio < 0.3) return team === 'enemy' ? 'cower' : 'idle_hurt'
  return team === 'enemy' ? 'idle_enemy' : 'idle'
}

/** Idle playback rate per archetype (heavy units breathe slowly, goblins fidget fast) with per-unit jitter in [0,1). */
export function idleRateFor(enemyId: EnemyArchetypeId | undefined, jitter: number): number {
  const base =
    enemyId === 'ignis_titan' ? 0.62
      : enemyId === 'frost_golem' || enemyId === 'magma_warden' ? 0.68
      : enemyId === 'frostwyrm_rimefang' ? 0.72
      : enemyId === 'orc_brute' || enemyId === 'river_troll' || enemyId === 'briar_warlord' || enemyId === 'abyssal_sentinel' ? 0.82
      : enemyId === 'goblin' || enemyId === 'bone_thrall' ? 1.25
      : enemyId === 'ice_wraith' ? 1.15
      : 1
  return base * (0.9 + jitter * 0.2)
}

