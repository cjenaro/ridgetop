type Archetype = 'bow' | 'heavy' | 'stab' | 'caster' | 'blade'

function archetypeOf(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): Archetype {
  if (heroId === 'archer' || enemyId === 'bone_archer') return 'bow'
  if (enemyId === 'orc_brute' || heroId === 'champion' || enemyId === 'crypt_knight' || enemyId === 'frost_golem') return 'heavy'
  if (heroId === 'rogue' || enemyId === 'goblin') return 'stab'
  if (
    heroId === 'mage' || heroId === 'cryomancer' || heroId === 'cleric' ||
    enemyId === 'bog_shaman' || enemyId === 'eclipse_archon'
  ) return 'caster'
  return 'blade'
}

/** Basic attack clip with archetype-specific anticipation/strike/follow-through. */
export function attackClipFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): UnitClipName {
  const a = archetypeOf(heroId, enemyId)
  if (a === 'bow') return 'attack_bow'
  if (a === 'heavy') return 'attack_heavy'
  if (a === 'stab') return 'attack_stab'
  if (a === 'caster') return 'cast'
  return 'attack'
}

