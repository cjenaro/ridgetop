type Archetype = 'bow' | 'heavy' | 'stab' | 'caster' | 'blade'

function archetypeOf(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): Archetype {
  if (heroId === 'archer' || enemyId === 'bone_archer') return 'bow'
  if (
    enemyId === 'orc_brute' || heroId === 'champion' || enemyId === 'crypt_knight' || enemyId === 'frost_golem' ||
    enemyId === 'river_troll' || enemyId === 'briar_warlord' || enemyId === 'frost_jarl' || enemyId === 'magma_warden' ||
    enemyId === 'dune_sovereign_boss' || enemyId === 'frostwyrm_rimefang' || enemyId === 'ignis_titan' || enemyId === 'abyssal_sentinel'
  ) return 'heavy'
  if (heroId === 'rogue' || enemyId === 'goblin' || enemyId === 'bone_thrall') return 'stab'
  if (
    heroId === 'mage' || heroId === 'cryomancer' || heroId === 'cleric' ||
    enemyId === 'bog_shaman' || enemyId === 'eclipse_archon' ||
    enemyId === 'ember_pyromancer' || enemyId === 'ice_wraith' ||
    enemyId === 'bone_necromancer' || enemyId === 'mire_matriarch' || enemyId === 'ash_inquisitor' ||
    enemyId === 'lich_vaelen' || enemyId === 'astral_warden_boss' || enemyId === 'unbroken_crown_boss'
  ) return 'caster'
  return 'blade'
}

/** Locomotion style: drives the run clip and its stride-matched playback rate. */
export type Gait = 'normal' | 'heavy' | 'agile' | 'glide' | 'stomp'

export function gaitFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): Gait {
  if (
    heroId === 'knight' || heroId === 'paladin' || enemyId === 'crypt_knight' ||
    enemyId === 'frost_jarl' || enemyId === 'dune_sovereign_boss' || enemyId === 'abyssal_sentinel'
  ) return 'heavy'
  if (heroId === 'rogue' || enemyId === 'goblin' || enemyId === 'bone_thrall') return 'agile'
  if (
    heroId === 'mage' || heroId === 'cryomancer' || enemyId === 'eclipse_archon' ||
    enemyId === 'ice_wraith' || enemyId === 'ember_pyromancer' || enemyId === 'bone_necromancer' ||
    enemyId === 'mire_matriarch' || enemyId === 'ash_inquisitor' || enemyId === 'lich_vaelen' ||
    enemyId === 'astral_warden_boss' || enemyId === 'unbroken_crown_boss'
  ) return 'glide'
  if (
    enemyId === 'frost_golem' || enemyId === 'orc_brute' ||
    enemyId === 'river_troll' || enemyId === 'briar_warlord' ||
    enemyId === 'magma_warden' || enemyId === 'frostwyrm_rimefang' || enemyId === 'ignis_titan'
  ) return 'stomp'
  return 'normal'
}

const RUN_CLIP: Readonly<Record<Gait, UnitClipName>> = {
  normal: 'run', heavy: 'run_heavy', agile: 'run_agile', glide: 'run_glide', stomp: 'run_stomp'
}
/** Tiles covered per footfall for each gait (heavy = short firm strides, stomp = long lumbering ones). */
const RUN_STRIDE: Readonly<Record<Gait, number>> = { normal: 1, heavy: 0.8, agile: 0.85, glide: 1.3, stomp: 1.4 }
/** Board movement speed in tiles per second. */
const MOVE_TILES_PER_SECOND = 5.2

export function runClipFor(gait: Gait): UnitClipName {
  return RUN_CLIP[gait]
}

/** Playback rate so each loop (2 footfalls) covers 2 strides at board speed and feet don't skate. */
export function runRateFor(gait: Gait): number {
  return (UNIT_CLIPS[RUN_CLIP[gait]].duration / 2) * MOVE_TILES_PER_SECOND / RUN_STRIDE[gait]
}

