const STANCE_CACHE = new Map<string, Record<string, JointPose>>()

function buildStance(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): Record<string, JointPose> {
  if (heroId === 'knight' || heroId === 'paladin' || enemyId === 'crypt_knight') {
    return {
      body: { rotation: [0.04, -0.14, 0] },
      armL: { rotation: [-0.42, 0.22, -0.12] },
      armR: { rotation: [-0.36, -0.14, 0.14] },
      cape: { rotation: [0.08, 0, 0] }
    }
  }
  if (heroId === 'archer' || enemyId === 'bone_archer') {
    return {
      body: { rotation: [0.03, 0.18, 0] },
      head: { rotation: [0, -0.14, 0] },
      armL: { rotation: [-0.72, -0.14, -0.10] },
      armR: { rotation: [-0.48, 0.20, 0.08] }
    }
  }
  if (heroId === 'mage' || heroId === 'cryomancer' || heroId === 'cleric' || enemyId === 'bog_shaman' || enemyId === 'eclipse_archon') {
    return {
      body: { rotation: [0.02, -0.06, 0] },
      armL: { rotation: [-0.46, 0.14, -0.16] },
      armR: { rotation: [-0.28, 0, 0.12] },
      cape: { rotation: [0.06, 0, 0] }
    }
  }
  if (heroId === 'rogue' || heroId === 'champion') {
    return {
      body: { rotation: [0.10, -0.16, 0] },
      armL: { rotation: [-0.44, 0.20, -0.18] },
      armR: { rotation: [-0.54, -0.18, 0.20] },
      cape: { rotation: [0.10, 0, 0] }
    }
  }
  if (enemyId === 'orc_brute' || enemyId === 'frost_golem') {
    return {
      body: { rotation: [0.10, 0, 0] },
      armL: { rotation: [-0.20, 0, -0.28] },
      armR: { rotation: [-0.30, 0, 0.28] },
      legL: { rotation: [0, 0, -0.08] },
      legR: { rotation: [0, 0, 0.08] }
    }
  }
  return {
    body: { rotation: [0.06, 0, 0] },
    armL: { rotation: [-0.24, 0, -0.12] },
    armR: { rotation: [-0.36, 0, 0.14] }
  }
}

/** Combat-ready stance offsets layered onto idle using canonical character-builder joints (cached, do not mutate). */
export function stanceOffsetFor(heroId?: HeroClassId, enemyId?: EnemyArchetypeId): Record<string, JointPose> {
  const key = `${heroId ?? ''}:${enemyId ?? ''}`
  let stance = STANCE_CACHE.get(key)
  if (!stance) {
    stance = buildStance(heroId, enemyId)
    STANCE_CACHE.set(key, stance)
  }
  return stance
}

